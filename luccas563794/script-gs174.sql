CREATE TABLE GS174_BAIRRO (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME            VARCHAR2(80)  NOT NULL,
  ZONA            VARCHAR2(10)  NOT NULL,
  POSSUI_PISCINAO NUMBER(1)     DEFAULT 0,
  CONSTRAINT CK_GS174_BAIRRO_ZONA CHECK (ZONA IN ('Centro', 'Norte', 'Sul', 'Leste', 'Oeste')),
  CONSTRAINT CK_GS174_BAIRRO_PISC CHECK (POSSUI_PISCINAO IN (0, 1))
);

CREATE TABLE GS174_TRECHO (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LOGRADOURO   VARCHAR2(120) NOT NULL,
  TIPO_CALCADA VARCHAR2(20)  NOT NULL,
  ALTITUDE     NUMBER(4)     NOT NULL,
  BAIRRO_ID    NUMBER        NOT NULL,
  CONSTRAINT FK_GS174_TRECHO_BAIRRO FOREIGN KEY (BAIRRO_ID)
    REFERENCES GS174_BAIRRO (ID),
  CONSTRAINT CK_GS174_TRECHO_ALT CHECK (ALTITUDE BETWEEN 0 AND 2000)
);

CREATE TABLE GS174_LEITURA (
  ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  DATA_HORA DATE          NOT NULL,
  LAMINA_CM NUMBER(3)     NOT NULL,
  STATUS    VARCHAR2(10)  NOT NULL,
  TRECHO_ID NUMBER        NOT NULL,
  CONSTRAINT FK_GS174_LEITURA_TRECHO FOREIGN KEY (TRECHO_ID)
    REFERENCES GS174_TRECHO (ID),
  CONSTRAINT CK_GS174_LEITURA_LAMINA CHECK (LAMINA_CM BETWEEN 0 AND 300),
  CONSTRAINT CK_GS174_LEITURA_STATUS CHECK (STATUS IN ('NORMAL', 'ATENCAO', 'ALERTA'))
);

